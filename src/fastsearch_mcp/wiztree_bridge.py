"""WizTree MFT bridge for FastSearch MCP.

Provides direct NTFS MFT search via Antibody Software's WizTree CLI.
Bypasses the custom C++ Windows service and named pipe when unavailable,
providing rock-solid, sub-second MFT search across local drives.
"""

import asyncio
import csv
import logging
import os
import shutil
import string
import subprocess
import tempfile
from pathlib import Path
from typing import Any

logger = logging.getLogger(__name__)

# Known install locations for WizTree on Windows
WIZTREE_CANDIDATE_PATHS = [
    Path(r"C:\Program Files\WizTree\WizTree64.exe"),
    Path(r"C:\Program Files\WizTree\WizTree.exe"),
    Path(r"C:\Program Files (x86)\WizTree\WizTree64.exe"),
    Path(r"C:\Program Files (x86)\WizTree\WizTree.exe"),
]


def get_wiztree_path() -> Path | None:
    """Return the absolute path to WizTree executable if installed, else None."""
    for candidate in WIZTREE_CANDIDATE_PATHS:
        if candidate.is_file():
            return candidate

    # Also check PATH
    which_path = shutil.which("WizTree64.exe") or shutil.which("WizTree.exe")
    if which_path:
        return Path(which_path)

    return None


def is_wiztree_available() -> bool:
    """Return True if WizTree executable is found on system."""
    return get_wiztree_path() is not None


def get_local_drives() -> list[str]:
    """Detect available local fixed drive letters (e.g. ['C:\\', 'D:\\', ...])."""
    drives: list[str] = []
    try:
        import win32file

        mask = win32file.GetLogicalDrives()
        for i, letter in enumerate(string.ascii_uppercase):
            if mask & (1 << i):
                root = f"{letter}:\\"
                if win32file.GetDriveType(root) == win32file.DRIVE_FIXED:
                    drives.append(root)
    except Exception:
        try:
            import ctypes

            kernel32 = ctypes.windll.kernel32
            mask = kernel32.GetLogicalDrives()
            for i, letter in enumerate(string.ascii_uppercase):
                if mask & (1 << i):
                    root = f"{letter}:\\"
                    if kernel32.GetDriveTypeW(root) == 3:  # DRIVE_FIXED
                        drives.append(root)
        except Exception:
            pass

    return drives or ["C:\\"]


def _search_single_drive_sync(
    wiztree_exe: Path,
    drive: str,
    pattern: str,
    max_results: int = 1000,
    timeout_sec: float = 30.0,
) -> list[dict[str, Any]]:
    """Synchronously execute WizTree against a single drive and parse CSV results."""
    # Ensure drive has backslash, e.g. "E:\"
    drive_norm = drive.strip()
    if len(drive_norm) == 2 and drive_norm[1] == ":":
        drive_norm += "\\"
    elif not drive_norm.endswith("\\"):
        drive_norm += "\\"

    # Create unique temp CSV output
    with tempfile.NamedTemporaryFile(suffix=".csv", delete=False) as tmp:
        temp_csv_path = tmp.name

    try:
        # WizTree command line:
        # wiztree64.exe "<drive>" /filter="<pattern>" /export="<csv>" /admin=0 /exportfolders=0
        cmd = [
            str(wiztree_exe),
            drive_norm,
            f"/filter={pattern}",
            f"/export={temp_csv_path}",
            "/admin=0",
            "/exportfolders=0",
        ]

        logger.info(f"Running WizTree search on {drive_norm} for '{pattern}'")

        subprocess.run(
            cmd,
            capture_output=True,
            timeout=timeout_sec,
            check=False,
        )

        if not os.path.exists(temp_csv_path) or os.path.getsize(temp_csv_path) == 0:
            logger.debug(f"WizTree returned empty or non-existent file for drive {drive_norm}")
            return []

        results: list[dict[str, Any]] = []
        with open(temp_csv_path, encoding="utf-8-sig", errors="replace") as f:
            # Read first line - might contain "Generated by WizTree..."
            first_line = f.readline()
            if not first_line.startswith("File Name,"):
                # Header was on line 2, so leave cursor at line 2
                pass
            else:
                f.seek(0)

            reader = csv.DictReader(f)
            for row in reader:
                file_path = row.get("File Name") or row.get("FileName")
                if not file_path:
                    continue

                try:
                    size_bytes = int(row.get("Size") or row.get("Allocated") or 0)
                except ValueError:
                    size_bytes = 0

                mod_time = row.get("Modified", "")
                attrs = row.get("Attributes", "")

                item = {
                    "path": file_path,
                    "name": os.path.basename(file_path),
                    "size": size_bytes,
                    "modified": mod_time,
                    "created": mod_time,
                    "attributes": attrs,
                }
                results.append(item)

                if max_results > 0 and len(results) >= max_results:
                    break

        return results

    except Exception as e:
        logger.error(f"Error executing WizTree on {drive_norm}: {e}")
        return []
    finally:
        if os.path.exists(temp_csv_path):
            try:
                os.remove(temp_csv_path)
            except OSError:
                pass


async def search_files_wiztree(
    pattern: str,
    directory: str = "*",
    max_results: int = 1000,
    search_all: bool = False,
) -> dict[str, Any]:
    """Execute high-speed MFT file search using the WizTree CLI bridge.

    Args:
        pattern: Wildcard / search pattern (e.g. '*.py', '*Foster*', 'README*')
        directory: Drive letter or path ('C:\\', 'E:\\', or '*' for all drives)
        max_results: Maximum matching results to return (default: 1000)
        search_all: Whether to scan all connected local NTFS drives

    Returns:
        dict: Standard FastSearch response format containing 'results', 'count', and metadata.
    """
    wiztree_exe = get_wiztree_path()
    if not wiztree_exe:
        raise RuntimeError("WizTree is not installed or accessible on this system.")

    target_drives: list[str] = []
    directory_clean = directory.strip()

    if search_all or directory_clean in ("*", "all", "ALL", ""):
        target_drives = get_local_drives()
    else:
        # Extract drive from path (e.g., "D:\Projects" -> "D:\")
        drive_prefix = os.path.splitdrive(directory_clean)[0]
        if drive_prefix:
            target_drives = [f"{drive_prefix}\\"]
        else:
            target_drives = ["C:\\"]

    all_results: list[dict[str, Any]] = []

    # Run searches across target drives
    for drive in target_drives:
        remaining = max_results - len(all_results) if max_results > 0 else 0
        if max_results > 0 and remaining <= 0:
            break

        drive_results = await asyncio.to_thread(
            _search_single_drive_sync,
            wiztree_exe,
            drive,
            pattern,
            max_results=remaining if max_results > 0 else 0,
        )

        # If a specific subfolder was requested rather than whole drive, filter by prefix
        if directory_clean and directory_clean not in ("*", "all", "ALL") and len(directory_clean) > 3:
            norm_dir = os.path.normpath(directory_clean).lower()
            drive_results = [r for r in drive_results if os.path.normpath(r["path"]).lower().startswith(norm_dir)]

        all_results.extend(drive_results)

    return {
        "success": True,
        "results": all_results,
        "count": len(all_results),
        "pattern": pattern,
        "path": directory,
        "backend": "wiztree_mft",
        "drives_searched": target_drives,
    }
